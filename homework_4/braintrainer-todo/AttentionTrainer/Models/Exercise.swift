import Foundation

// MARK: - Типы упражнений

/// Перечисление всех доступных типов упражнений (мини-игр)
///
/// ## Доступные игры:
/// - **schulte**: Таблица Шульте — развитие периферийного зрения
/// - **nback**: N-Back — тренировка рабочей памяти
/// - **numbers**: Поиск чисел — развитие внимания и скорости
/// - **colors**: Поиск цветов — визуальная обработка
/// - **stroop**: Stroop-тест — подавление автоматической реакции
/// - **sequence**: Запомни последовательность — кратковременная память
///
/// ## Использование:
/// ```swift
/// let exercise: ExerciseType = .schulte
/// print(exercise.title) // "Таблица Шульте"
/// print(exercise.icon)  // "grid"
/// ```
enum ExerciseType: String, CaseIterable, Identifiable {
    // MARK: - Случаи
    
    /// Таблица Шульте
    /// Поиск чисел по порядку в случайной сетке
    case schulte = "schulte"
    
    /// N-Back
    /// Запоминание последовательности стимулов
    case nback = "nback"
    
    /// Поиск чисел
    /// Поиск совпадающих чисел в двух колонках
    case numbers = "numbers"
    
    /// Поиск цветов
    /// Поиск совпадающих цветов в двух колонках
    case colors = "colors"
    
    /// Stroop-тест
    /// Выбор цвета текста, игнорируя написанное слово
    case stroop = "stroop"
    
    /// Запомни последовательность
    /// Повторение показанного порядка цветов
    case sequence = "sequence"
    
    // MARK: - Свойства
    
    /// Уникальный идентификатор (rawValue)
    var id: String { rawValue }
    
    /// Отображаемое название игры
    var title: String {
        switch self {
        case .schulte: return "Таблица Шульте"
        case .nback: return "N-Back"
        case .numbers: return "Поиск чисел"
        case .colors: return "Поиск цветов"
        case .stroop: return "Stroop-тест"
        case .sequence: return "Последовательность"
        }
    }
    
    /// Краткое описание для карточки игры
    var description: String {
        switch self {
        case .schulte:
            return "Развитие периферийного зрения и скорости восприятия"
        case .nback:
            return "Тренировка рабочей памяти и концентрации"
        case .numbers:
            return "Поиск повторяющихся чисел с помощью периферийного зрения"
        case .colors:
            return "Поиск совпадающих цветов"
        case .stroop:
            return "Выберите цвет текста, не читая слово"
        case .sequence:
            return "Запомните и повторите последовательность цветов"
        }
    }
    
    /// Иконка SF Symbols для игры
    var icon: String {
        switch self {
        case .schulte: return "grid"
        case .nback: return "brain"
        case .numbers: return "number"
        case .colors: return "paintpalette"
        case .stroop: return "textformat"
        case .sequence: return "square.grid.3x3"
        }
    }
    
    /// Навыки, которые развивает эта игра
    ///
    /// Используется для расчета прогресса навыков в UserStats
    var targetSkills: [String] {
        switch self {
        case .schulte:
            return ["Периферийное зрение", "Скорость восприятия"]
        case .nback:
            return ["Рабочая память", "Концентрация"]
        case .numbers:
            return ["Периферийное зрение", "Кратковременная память"]
        case .colors:
            return ["Периферийное зрение", "Визуальная обработка"]
        case .stroop:
            return ["Концентрация", "Когнитивный контроль"]
        case .sequence:
            return ["Кратковременная память", "Рабочая память"]
        }
    }
    
    /// Подробные инструкции для игрока
    ///
    /// Отображается при нажатии на кнопку ℹ️ в игре
    var detailedInstructions: String {
        switch self {
        case .schulte:
            return """
            📋 **Правила игры**
            
            Найдите числа от 1 до максимального по порядку как можно быстрее.
            
            **Как играть:**
            • Нажимайте на числа в порядке возрастания (1, 2, 3...)
            • Используйте периферийное зрение — не задерживайте взгляд на одной цифре
            • Старайтесь видеть всё поле одновременно
            • Ошибки учитываются — старайтесь быть внимательным
            
            **Уровни сложности:**
            • Лёгкий: поле 5×5
            • Средний: поле 7×7
            • Сложный: поле 9×9
            
            **Совет:** Не водите глазами по каждой цифре. Расслабьте взгляд и «ловите» нужные числа боковым зрением.
            """
        case .nback:
            return """
            📋 **Правила игры**
            
            Тренировка рабочей памяти. Нажимайте «Совпадение!», когда текущая буква совпадает с той, что была N шагов назад.
            
            **Как играть:**
            • Буквы появляются последовательно
            • Сравните текущую букву с буквой N шагов назад
            • При совпадении нажмите кнопку «Совпадение!»
            • Реагируйте быстро — у вас ограниченное время
            
            **Пример (2-back):**
            Последовательность: A → B → **C** → B → **C**
            Когда появится второе C (через 2 шага после первого) — это совпадение!
            
            **Уровни сложности:**
            • Лёгкий: 1-back (сравнение с предыдущей)
            • Средний: 2-back
            • Сложный: 3-back
            """
        case .numbers:
            return """
            📋 **Правила игры**
            
            Найдите числа из центральной панели в левой и правой колонках.
            
            **Как играть:**
            • В центре показаны числа, которые нужно найти
            • Ищите эти числа в левой и правой колонках
            • Нажмите на число слева, затем на такое же справа
            • Найденная пара исчезает из центра
            
            **Важно:**
            • Сначала нажмите число в одной колонке
            • Затем нажмите такое же число в другой колонке
            • Ошибки штрафуются — выбирайте внимательно
            
            **Уровни сложности:**
            • Лёгкий: мало чисел, простые комбинации
            • Средний: больше чисел
            • Сложный: много чисел, сложные комбинации
            
            **Совет:** Используйте периферийное зрение. Не смотрите по очереди на каждое число — старайтесь видеть обе колонки сразу.
            """
        case .colors:
            return """
            📋 **Правила игры**
            
            Найдите цвета, которые есть в обеих колонках — левой и правой.
            
            **Как играть:**
            • Сравните цвета в левой и правой колонках
            • Найдите цвета, которые присутствуют в обеих колонках
            • Нажмите на совпадающий цвет в любой колонке
            • Найдите все пары цветов
            
            **Важно:**
            • Цвет должен присутствовать и слева, и справа
            • Каждая пара засчитывается один раз
            • Ошибки штрафуются
            
            **Уровни сложности:**
            • Лёгкий: мало цветов, яркие оттенки
            • Средний: больше цветов, похожие оттенки
            • Сложный: много цветов, сложные оттенки
            
            **Совет:** Не фокусируйтесь на одной колонке. Расслабьте взгляд и сравнивайте цвета обеих колонок одновременно.
            """
        case .stroop:
            return """
            📋 **Правила игры**
            
            На экране появляется слово с названием цвета, но окрашено оно может быть другим цветом.
            
            **Как играть:**
            • Игнорируйте написанное слово
            • Выбирайте именно цвет текста
            • Отвечайте быстро и без ошибок
            
            **Пример:**
            Если слово «Красный» написано синим цветом, правильный ответ — «Синий».
            
            **Уровни сложности:**
            • Чем выше уровень, тем больше раундов и быстрее нужно реагировать.
            """
        case .sequence:
            return """
            📋 **Правила игры**
            
            Запомните порядок подсветки цветов и повторите его.
            
            **Как играть:**
            • Нажмите «Начать»
            • Дождитесь показа последовательности
            • Повторите цвета в том же порядке
            • Ошибки учитываются в точности результата
            
            **Уровни сложности:**
            • Чем выше уровень, тем длиннее последовательность и больше вариантов цветов.
            """
        }
    }
}

// MARK: - Игровая сессия

/// Структура для хранения информации об одной игровой сессии
///
/// Содержит метаданные игры: тип, уровень, время начала/окончания
/// Отличается от GameResult тем, что содержит только метрики,
/// а GameResult — итоговые вычисленные значения
struct ExerciseSession: Identifiable {
    
    /// Уникальный идентификатор сессии
    let id = UUID()
    
    /// Тип упражнения
    let exerciseType: ExerciseType
    
    /// Уровень сложности
    let difficulty: DifficultyLevel
    
    /// Время начала сессии
    let startTime: Date
    
    /// Время окончания (nil если игра еще идет)
    var endTime: Date?
    
    /// Метрики игры (nil если игра еще идет)
    var metrics: SessionMetrics?
    
    /// Продолжительность игры
    /// Вычисляется как разница между endTime и startTime
    var duration: TimeInterval? {
        guard let end = endTime else { return nil }
        return end.timeIntervalSince(startTime)
    }
}

// MARK: - Метрики сессии

/// Структура для хранения метрик игровой сессии
///
/// Содержит все числовые показатели одной игры.
/// Используется для создания GameResult и анализа прогресса.
struct SessionMetrics {
    
    /// Общее время игры в секундах
    let totalTime: TimeInterval
    
    /// Количество правильных ответов
    let correctAnswers: Int
    
    /// Количество неправильных ответов
    let incorrectAnswers: Int
    
    /// Среднее время реакции в секундах
    let averageReactionTime: TimeInterval
    
    /// Точность (0.0 - 1.0)
    /// correctAnswers / (correctAnswers + incorrectAnswers)
    let accuracy: Double
    
    /// Общее количество попыток
    var totalAttempts: Int {
        correctAnswers + incorrectAnswers
    }
    
    /// Счёт производительности (0-100)
    ///
    /// Формула: комбинация точности и скорости
    /// - Точность дает 70% веса
    /// - Скорость дает 30% веса (нормализована по 30 секундам)
    var performanceScore: Double {
        let speedScore = min(1.0, 30.0 / totalTime)
        return (accuracy * 0.7 + speedScore * 0.3) * 100
    }
}
